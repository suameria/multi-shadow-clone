from typing import Protocol


class StudyStore(Protocol):
    def reserve(self, key: str, record: dict) -> bool: ...
    def save(self, key: str, record: dict) -> None: ...
    def read(self, key: str) -> dict | None: ...
    def list_records(self) -> list[dict]: ...


class CandidateJobs(Protocol):
    def create(self, objective: str, sources: dict, arm: str, maximum_turns: int) -> str: ...
    def run(self, run_id: str) -> dict: ...
    def stop(self, run_id: str) -> None: ...
